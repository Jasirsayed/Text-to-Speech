  async function peaksFrom(buffer, n = 600) {
    try {
      const decoded = await ctx.decodeAudioData(buffer);
      const data = decoded.getChannelData(0);
      const step = Math.max(1, Math.floor(data.length / n));
      const out = new Float32Array(n);
      let max = 0;
      for (let i = 0; i < n; i++) {
        let peak = 0;
        for (let j = i * step, end = Math.min(data.length, j + step); j < end; j++) {
          const v = Math.abs(data[j]); if (v > peak) peak = v;
        }
        out[i] = peak; if (peak > max) max = peak;
      }
      if (max > 0) for (let i = 0; i < n; i++) out[i] /= max;
      return { peaks: out, duration: decoded.duration };
    } catch (e) {
      return { peaks: null, duration: 0 };
    }
  }

